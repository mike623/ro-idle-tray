// Regenerate src/atlas-data.js from the live game bundle: `node scripts/extract-maps.mjs`.
// Evaluates only the game's static data literal ({version:1,items:[...],...,maps:[...]})
// in an empty VM context. Minified names change per game build, so match the shape.
import fs from 'fs';
import vm from 'vm';

const html = await (await fetch('https://ro-idle.app/')).text();
const js = html.match(/\/assets\/index-[^"]+\.js/)?.[0];
if (!js) throw new Error('game bundle not found in index.html');
const s = await (await fetch(`https://ro-idle.app${js}`)).text();

const start = s.indexOf('{version:1,items:[');
if (start < 0) throw new Error('game data literal not found');
let depth = 0, i = start, q = null;
for (; i < s.length; i++) {
  const ch = s[i];
  if (q) { if (ch === '\\') i++; else if (ch === q) q = null; continue; }
  if (ch === '`' || ch === '"' || ch === "'") q = ch;
  else if (ch === '{' || ch === '[') depth++;
  else if (ch === '}' || ch === ']') { depth--; if (depth === 0) break; }
}
const data = vm.runInNewContext(`(${s.slice(start, i + 1)})`, Object.create(null), { timeout: 2000 });

// Assistant data and party rules come from the same live build as the atlas.
const partyBonus = s.match(/隊員每多 1 人，經驗 \+`,(\d+),`%（最多 \+`,(\d+),`%/);
const shareLimit = s.match(/隊員 Base Level 差距超過 `,(\d+),` 時不能均分/);
if (!partyBonus || !shareLimit || !data.skills?.length || !data.monsters?.length || !data.maps?.length) {
  throw new Error('game data or party-rule shape changed; no files refreshed');
}
const finite = value => typeof value === 'number' && Number.isFinite(value);
if (!data.monsters.every(m => Number.isInteger(m.id) && typeof m.name === 'string' && finite(m.hp) && m.hp > 0 && finite(m.baseExp) && Array.isArray(m.atk) && m.atk.length === 2 && m.atk.every(finite))
    || !data.maps.every(m => typeof m.id === 'string' && typeof m.name === 'string' && [...(m.spawns ?? []), ...(m.timed ?? [])].every(x => Number.isInteger(x.monsterId) && finite(x.count) && x.count > 0))
    || !data.skills.every(skill => typeof skill.id === 'string' && typeof skill.name === 'string')) {
  throw new Error('game record shape changed; no files refreshed');
}
const items = new Map(data.items.map(item => [item.id, item.name]));
const knowledge = {
  source: `https://ro-idle.app${js}`, updatedAt: new Date().toISOString(),
  partyRules: {bonusPerMember: Number(partyBonus[1]) / 100, maxBonus: Number(partyBonus[2]) / 100, evenShareLevelLimit: Number(shareLimit[1])},
  monsters: data.monsters.map(monster => ({...monster,
    drops: (monster.drops ?? []).map(drop => ({...drop, name: items.get(drop.itemId) ?? null})),
  })), maps: data.maps, skills: data.skills,
};
const mon = new Map([...(data.summons ?? []), ...data.monsters].map(m => [m.id, m]));
const boss = id => ({ boss: 1, mvp: 2 })[mon.get(id)?.boss] ?? 0;
const nm = id => mon.get(id)?.name ?? `#${id}`;
const lv = id => mon.get(id)?.lv ?? 0;
// [id, name, type, travelSec, connections, spawns[[name, lv, count, boss]], timed[[name, lv, count, respawnMin, varianceMin, boss]]]
const maps = data.maps.map(m => [
  m.id, m.name, m.type, Math.round((m.travelFromTownMs ?? 0) / 1000), m.connections ?? [],
  (m.spawns ?? []).map(x => [nm(x.monsterId), lv(x.monsterId), x.count, boss(x.monsterId)]),
  (m.timed ?? []).map(x => [nm(x.monsterId), lv(x.monsterId), x.count,
    +(x.respawnMs / 60000).toFixed(1), +(x.varianceMs / 60000).toFixed(1), boss(x.monsterId)]),
]);
const today = new Date().toISOString().slice(0, 10);
const json = JSON.stringify(maps).replace(/</g, '\\u003c');
const outputs = [
  // Item editor (src/items.html) names and hover cards; kept out of game-data.json so the assistant's lookup kinds stay as they are.
  [new URL('../src/item-info.json', import.meta.url), JSON.stringify(Object.fromEntries(data.items.map(({id, name, desc, weight, sell}) => [id, {name, desc, weight, sell}])))],
  [new URL('../src/atlas-data.js', import.meta.url), `// Generated by scripts/extract-maps.mjs from ${js} on ${today}. Do not edit.\nconst MAPS_UPDATED = ${JSON.stringify(today)};\nconst MAPS = ${json};\n`],
  [new URL('../src/game-data.json', import.meta.url), JSON.stringify(knowledge)],
];
const staged = [];
try {
  for (const [url, text] of outputs) {
    const temp = new URL(url); temp.pathname += `.${process.pid}.tmp`;
    fs.writeFileSync(temp, text, {flag:'wx'}); staged.push([temp,url]);
  }
  // Both complete outputs exist before replacing either published artifact.
  for (const [temp,url] of staged) fs.renameSync(temp,url);
} finally {
  for (const [temp] of staged) fs.rmSync(temp,{force:true});
}
console.log(`${maps.length} maps, ${knowledge.monsters.length} monsters and ${knowledge.skills.length} skills refreshed from ${js}`);
